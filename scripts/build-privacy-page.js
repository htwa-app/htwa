#!/usr/bin/env node
/**
 * scripts/build-privacy-page.js
 *
 * Renders legal/privacy-policy.md → website/privacy/index.html (served by Netlify
 * at htwa-app.com/privacy). The first-contact SMS sent to nominated contacts
 * (supabase/functions/_shared/contactNotice.ts) links to this URL as the full
 * Article 14 notice (§4A), so it has to exist.
 *
 * Dependency-free on purpose (the policy only uses headings, paragraphs, bold,
 * links, bullet lists, one table and rules). Internal `<!-- ADVISER NOTE -->`
 * comments are STRIPPED — they must never appear on a public page.
 *
 * Usage:  node scripts/build-privacy-page.js
 * Sync is enforced by __tests__/unit/privacyPage.test.ts (like constants/legalDocs.ts).
 */

const fs = require('fs');
const path = require('path');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function inline(text) {
  return esc(text)
    .replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+|mailto:[^)\s]+)\)/g, '<a href="$2">$1</a>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[\s(])\*([^*\s][^*]*)\*(?=[\s).,;:]|$)/g, '$1<em>$2</em>')
    .replace(/`([^`]+)`/g, '<code>$1</code>');
}

function renderList(lines, start) {
  // Bullet lists, nested by 2-space indentation.
  const html = [];
  const stack = [];
  let i = start;
  for (; i < lines.length; i++) {
    const m = lines[i].match(/^(\s*)- (.*)$/);
    if (!m) break;
    const depth = Math.floor(m[1].length / 2);
    while (stack.length > depth + 1) { html.push('</li></ul>'); stack.pop(); }
    if (stack.length === depth + 1) { html.push('</li>'); }
    else { while (stack.length < depth + 1) { html.push('<ul>'); stack.push(true); } }
    html.push(`<li>${inline(m[2])}`);
  }
  while (stack.length) { html.push('</li></ul>'); stack.pop(); }
  return { html: html.join(''), next: i };
}

function renderTable(lines, start) {
  const rows = [];
  let i = start;
  for (; i < lines.length && /^\|/.test(lines[i]); i++) rows.push(lines[i]);
  const cells = (r) => r.replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
  const [head, , ...body] = rows;
  const th = cells(head).map((c) => `<th>${inline(c)}</th>`).join('');
  const trs = body.map((r) => `<tr>${cells(r).map((c) => `<td>${inline(c)}</td>`).join('')}</tr>`).join('');
  return { html: `<div class="table-wrap"><table><thead><tr>${th}</tr></thead><tbody>${trs}</tbody></table></div>`, next: i };
}

function markdownToHtml(md) {
  const lines = md.replace(/<!--[\s\S]*?-->/g, '').replace(/\r\n/g, '\n').split('\n').map((l) => l.replace(/ {2,}$/, (m) => m)); // keep trailing double-space for <br>
  const out = [];
  let para = [];
  const flush = () => {
    if (para.length) { out.push(`<p>${para.map((l, idx) => inline(l.replace(/ {2,}$/, '')) + (/ {2,}$/.test(l) && idx < para.length - 1 ? '<br>' : '')).join(' ')}</p>`); para = []; }
  };
  for (let i = 0; i < lines.length; ) {
    const line = lines[i];
    if (/^\s*$/.test(line)) { flush(); i++; continue; }
    const h = line.match(/^(#{1,3}) (.*)$/);
    if (h) { flush(); out.push(`<h${h[1].length}>${inline(h[2])}</h${h[1].length}>`); i++; continue; }
    if (/^---+\s*$/.test(line)) { flush(); out.push('<hr>'); i++; continue; }
    if (/^\|/.test(line)) { flush(); const t = renderTable(lines, i); out.push(t.html); i = t.next; continue; }
    if (/^\s*- /.test(line)) { flush(); const l = renderList(lines, i); out.push(l.html); i = l.next; continue; }
    para.push(line); i++;
  }
  flush();
  return out.join('\n');
}

function buildPrivacyHtml(md) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<!-- Draft policy pending legal adviser review (ADVISER-BRIEFING.md): keep out of search indexes until signed off. -->
<meta name="robots" content="noindex">
<title>htwa. — privacy policy</title>
<!-- GENERATED by scripts/build-privacy-page.js from legal/privacy-policy.md — do not edit by hand. -->
<style>
  :root { --teal: #0F766E; --amber: #F59E0B; --text: #1A1A1A; --text-2: #555; --bg: #FAFAF7; --surface: #fff; --border: rgba(0,0,0,0.1); }
  * { box-sizing: border-box; }
  body { margin: 0; font-family: -apple-system, 'Segoe UI', Roboto, sans-serif; background: var(--bg); color: var(--text); line-height: 1.6; }
  .wrap { max-width: 720px; margin: 0 auto; padding: 28px 20px 64px; }
  .brand { font-weight: 700; font-size: 20px; margin-bottom: 8px; }
  .brand .dot { color: var(--amber); }
  h1 { font-size: 28px; line-height: 1.2; } h2 { font-size: 20px; margin-top: 2em; } h3 { font-size: 16px; }
  a { color: var(--teal); } hr { border: 0; border-top: 1px solid var(--border); margin: 2em 0; }
  ul { padding-left: 1.4em; } li { margin: 0.25em 0; }
  .table-wrap { overflow-x: auto; } table { border-collapse: collapse; width: 100%; font-size: 14px; background: var(--surface); }
  th, td { border: 1px solid var(--border); padding: 8px 10px; text-align: left; vertical-align: top; }
  th { background: #EEF4F3; }
</style>
</head>
<body>
<div class="wrap">
<div class="brand">htwa<span class="dot">.</span></div>
${markdownToHtml(md)}
</div>
</body>
</html>
`;
}

module.exports = { markdownToHtml, buildPrivacyHtml };

if (require.main === module) {
  const root = path.resolve(__dirname, '..');
  const md = fs.readFileSync(path.join(root, 'legal', 'privacy-policy.md'), 'utf8');
  const outDir = path.join(root, 'website', 'privacy');
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'index.html'), buildPrivacyHtml(md));
  console.log('wrote website/privacy/index.html');
}
